"""
Trace the Mografy "ribbon m" logo from docs/brand/logo-source.png into vector paths.

    python3 docs/brand/trace-logo.py

Writes:
  docs/brand/mografy-logo.svg          full lockup (mark + wordmark)
  docs/brand/mografy-mark.svg          mark only
  examples/mografy-intro/scenes/logo.ts  Path2D data per piece, for animating in a scene
  packages/web/src/logo.ts             mark paths for the player
Pieces: arch-left, ribbon (teal), arch-right, and one path per wordmark letter.
"""
import json, os
import cv2
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
INK, TEAL = '#151515', '#12B5A5'
SCALE = 4

src = Image.open(os.path.join(HERE, 'logo-source.png')).convert('RGB')
crop = src.crop((200, 360, 1370, 600))  # main lockup only
big = np.asarray(crop.resize((crop.width * SCALE, crop.height * SCALE), Image.LANCZOS)).astype(np.float32)
R, G, B = big[..., 0], big[..., 1], big[..., 2]
teal = ((G - R) > 80).astype(np.uint8) * 255
dark = ((255 - np.maximum(np.maximum(R, G), B)) > 128).astype(np.uint8) * 255
dark[teal > 0] = 0

def contours(mask):
    found, hierarchy = cv2.findContours(mask, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
    shapes = []  # (outer, [holes])
    if hierarchy is None:
        return shapes
    for i, c in enumerate(found):
        if hierarchy[0][i][3] == -1 and cv2.contourArea(c) > 400:
            holes = [found[j] for j in range(len(found)) if hierarchy[0][j][3] == i and cv2.contourArea(found[j]) > 100]
            shapes.append((c, holes))
    return shapes

def path(c):
    pts = cv2.approxPolyDP(c, 1.2, True)[:, 0, :] / SCALE
    return 'M' + 'L'.join(f'{x:.1f} {y:.1f}' for x, y in pts) + 'Z'

pieces = []
for c, holes in contours(teal):
    pieces.append(('ribbon', TEAL, c, holes))
dark_shapes = sorted(contours(dark), key=lambda s: cv2.boundingRect(s[0])[0])
mark_dark = [s for s in dark_shapes if cv2.boundingRect(s[0])[0] / SCALE < 430]
letters = [s for s in dark_shapes if cv2.boundingRect(s[0])[0] / SCALE >= 430]
assert len(mark_dark) == 2, f'expected two arches, got {len(mark_dark)}'
assert len(letters) == 7, f'expected 7 letters, got {len(letters)}'
pieces.insert(0, ('arch-left', INK, *mark_dark[0]))
pieces.insert(2, ('arch-right', INK, *mark_dark[1]))
for name, (c, holes) in zip('Mografy', letters):
    pieces.append((f'letter-{name}', INK, c, holes))

def bbox(items):
    xs, ys = [], []
    for _, _, c, _ in items:
        x, y, w, h = cv2.boundingRect(c)
        xs += [x / SCALE, (x + w) / SCALE]; ys += [y / SCALE, (y + h) / SCALE]
    return min(xs), min(ys), max(xs), max(ys)

out = [{'name': n, 'color': col, 'd': path(c) + ''.join(path(h) for h in holes), 'box': [round(v / SCALE, 1) for v in cv2.boundingRect(c)]} for n, col, c, holes in pieces]
full = bbox(pieces)
mark = bbox([p for p in pieces if not p[0].startswith('letter')])

def svg(items, box, pad=6):
    x0, y0, x1, y1 = box[0] - pad, box[1] - pad, box[2] + pad, box[3] + pad
    body = ''.join(f'<path fill="{p["color"]}" fill-rule="evenodd" d="{p["d"]}"/>' for p in items)
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x0:.1f} {y0:.1f} {x1 - x0:.1f} {y1 - y0:.1f}">{body}</svg>\n'

open(os.path.join(HERE, 'mografy-logo.svg'), 'w').write(svg(out, full))
open(os.path.join(HERE, 'mografy-mark.svg'), 'w').write(svg([p for p in out if not p['name'].startswith('letter')], mark))

header = '// Generated by docs/brand/trace-logo.py from docs/brand/logo-source.png. Do not edit by hand.\n'
scene = header + f'export const LOGO_INK = {json.dumps(INK)};\nexport const LOGO_TEAL = {json.dumps(TEAL)};\n'
scene += f'/** Bounds of the whole lockup and of the mark, in source pixels: [x0, y0, x1, y1]. */\nexport const LOGO_BOX = {json.dumps([round(v, 1) for v in full])};\nexport const MARK_BOX = {json.dumps([round(v, 1) for v in mark])};\n'
scene += '/** Pieces in drawing order: arch-left, ribbon, arch-right, then the letters of "Mografy". box = [x, y, w, h]. */\n'
scene += 'export const LOGO_PIECES: { name: string; color: string; d: string; box: [number, number, number, number] }[] = ' + json.dumps(out) + ';\n'
open(os.path.join(ROOT, 'examples', 'mografy-intro', 'scenes', 'logo.ts'), 'w').write(scene)

web = header + f'export const LOGO_VIEWBOX = "{full[0] - 2:.1f} {full[1] - 2:.1f} {full[2] - full[0] + 4:.1f} {full[3] - full[1] + 4:.1f}";\n'
web += f'export const MARK_VIEWBOX = "{mark[0] - 2:.1f} {mark[1] - 2:.1f} {mark[2] - mark[0] + 4:.1f} {mark[3] - mark[1] + 4:.1f}";\n'
web += '/** ribbon = the teal piece; every other piece takes the text colour. */\n'
web += 'export const LOGO_PIECES: { name: string; d: string }[] = ' + json.dumps([{'name': p['name'], 'd': p['d']} for p in out]) + ';\n'
open(os.path.join(ROOT, 'packages', 'web', 'src', 'logo.ts'), 'w').write(web)
print('pieces', [p['name'] for p in out], 'lockup', [round(v) for v in full], 'mark', [round(v) for v in mark])
print('sizes', {p['name']: len(p['d']) for p in out})
